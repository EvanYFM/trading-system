def convert(token):
    """'3472.57亿'→3.47257e11；'30.53万'→305300；'+4920'→4920；''→''"""
    token = str(token).strip().replace("+", "")
    if token in ("", "0", "-0"):
        return token
    if token.endswith("亿"):
        return int(round(float(token[:-1]) * 1e8))
    if token.endswith("万"):
        return int(round(float(token[:-1]) * 1e4))
    try:
        return int(round(float(token)))
    except ValueError:
        return token


